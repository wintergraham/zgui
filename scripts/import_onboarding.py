#!/usr/bin/env python3
"""Refresh the onboarding example's browser logos, keychain prompt and icons.

`design` is the ask-designs checkout holding ask.pen. `exports` is a folder of
Pencil "html-css" exports of the "Ask · Onboarding" board's screens: the icons
come from them, as Pencil outlines its Feather glyphs into filled paths.
"""
import argparse
import hashlib
import json
import re
import shutil
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("design", type=Path, help="ask-designs checkout (the folder holding designs/ask.pen)")
parser.add_argument("exports", type=Path, help="folder of the board's html-css exports")
args = parser.parse_args()
designs = args.design.resolve() / "designs"
target = Path(__file__).resolve().parents[1] / "crates/zgui-script/examples/onboarding"
assets = target / "assets"
assets.mkdir(parents=True, exist_ok=True)

logos = ["chrome", "aside", "safari", "arc", "dia", "brave", "helium", "firefox", "comet", "vivaldi", "edge"]
for name in logos:
    shutil.copyfile(designs / f"assets/browsers/{name}.png", assets / f"{name}.png")
# The macOS keychain prompt the coach points into.
shutil.copyfile(designs / "image-7.png", assets / "keychain.png")

svg = re.compile(r'<svg\s[^>]*data-icon-name="([^"]+)"[^>]*viewBox="([^"]+)"[^>]*>(.*?)</svg>', re.S)
icons = {}
for page in sorted(args.exports.glob("*.html")):
    for name, box, body in svg.findall(page.read_text()):
        paths = re.findall(r'<path\s[^>]*\bd="([^"]+)"', body)
        icons.setdefault(name, (box, paths))
lines = ["-- Feather icons from ask.pen, as Pencil outlines them: filled paths in", "-- white for `tint`. Generated by scripts/import_onboarding.py.", "return {"]
for name in sorted(icons):
    box, paths = icons[name]
    body = "".join(f'<path d="{d}" fill="#fff"/>' for d in paths)
    lines.append(f'\t["{name}"] = [=[<svg xmlns="http://www.w3.org/2000/svg" viewBox="{box}">{body}</svg>]=],')
lines += ["}", ""]
(target / "icons.luau").write_text("\n".join(lines))

inputs = ["ask.pen", "shaders/bayer-dither.glsl", "shaders/onboarding-field.glsl", "shaders/splash-space.glsl"]
manifest = {"board": "Ask · Onboarding (A0B6S)", "source_inputs_sha256": {
    name: hashlib.sha256((designs / name).read_bytes()).hexdigest() for name in inputs
}}
(target / "source.json").write_text(json.dumps(manifest, indent=2) + "\n")
print(f"Imported {len(logos)} logos, the keychain prompt and {len(icons)} icons into {target}")
